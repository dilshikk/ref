"""Reply-клавиатуры админ-панели.

Правило: каждая кнопка есть ровно в одном разделе, а каждая настройка меняется
ровно в одном месте (проверяют tests/test_keyboard_handlers.py и
tests/test_limits_panel.py). Раньше одни и те же кнопки стояли в нескольких
разделах («💰 Тарифы», «🎁 Реферальные настройки», «⚙️ Настройки каналов»),
а лимит рефералов в час менялся в трёх местах.

Структура:
- 📊 Статистика — только просмотр цифр;
- 💰 Финансы — заявки, удержания, балансы, бонусы, отчёты (без настроек);
- 👥 Пользователи — поиск, списки, баланс, сообщение, админы и денежные админы;
- 📢 Каналы и группы — обязательные подписки, группа приглашений, группа логов;
- 📨 Рассылки;
- ⚙️ Настройки — все суммы, лимиты, чат выплат, тексты, опрос и команды;
- 📋 Логи.

«⬅️ Назад» в разделе ведёт в главное меню, «⬅️ К каналам» и «⬅️ К настройкам»
во вложенных меню — на шаг вверх. one_time_keyboard не используется (#98).

Тексты кнопок в ряду из двух — короткие: длинный текст Telegram переносит
на две строки, и ряд становится выше остальных (так было с
«🚫 Заблокированные пользователи»).
"""
from aiogram.types import ReplyKeyboardMarkup, KeyboardButton


def _kb(rows: list[list[str]]) -> ReplyKeyboardMarkup:
    return ReplyKeyboardMarkup(
        keyboard=[[KeyboardButton(text=text) for text in row] for row in rows],
        resize_keyboard=True,
    )


def reply_keyboard_for_admin() -> ReplyKeyboardMarkup:
    return _kb([
        ["📊 Статистика", "💰 Финансы"],
        ["👥 Пользователи", "📢 Каналы и группы"],
        ["📨 Рассылки", "⚙️ Настройки"],
        ["📋 Логи", "👤 Меню пользователя"],
    ])


